-- ProjectVault schema for PostgreSQL. Neon starter sample projects are preserved
-- under neon_sample_projects_legacy when their table conflicts with this schema.

CREATE EXTENSION IF NOT EXISTS pgcrypto;

CREATE TABLE IF NOT EXISTS colleges (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  college_name TEXT NOT NULL UNIQUE CHECK (char_length(btrim(college_name)) BETWEEN 2 AND 200),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS profiles (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  auth_user_id TEXT UNIQUE,
  email TEXT NOT NULL UNIQUE,
  full_name TEXT NOT NULL,
  role TEXT NOT NULL CHECK (role IN ('student', 'faculty', 'admin')),
  college_id BIGINT REFERENCES colleges(id),
  department TEXT NOT NULL DEFAULT 'Unassigned',
  student_faculty_id TEXT,
  batch TEXT,
  status TEXT NOT NULL DEFAULT 'Active' CHECK (status IN ('Pending', 'Active', 'Suspended')),
  email_verified_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS pending_student_profiles (
  email TEXT PRIMARY KEY,
  full_name TEXT NOT NULL CHECK (char_length(btrim(full_name)) BETWEEN 2 AND 120),
  college_id BIGINT NOT NULL REFERENCES colleges(id),
  role TEXT NOT NULL DEFAULT 'student' CHECK (role IN ('student', 'faculty')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE UNIQUE INDEX IF NOT EXISTS profiles_email_lower_unique_idx
  ON profiles (LOWER(email));

CREATE TABLE IF NOT EXISTS email_tokens (
  id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  profile_id UUID NOT NULL REFERENCES profiles(id) ON DELETE CASCADE,
  token_hash TEXT NOT NULL UNIQUE,
  purpose TEXT NOT NULL CHECK (purpose IN ('verify_email', 'reset_password', 'invite')),
  expires_at TIMESTAMPTZ NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS email_tokens_profile_purpose_idx
  ON email_tokens(profile_id, purpose);

DO $$
BEGIN
  IF to_regclass('public.projects') IS NOT NULL
     AND NOT EXISTS (
       SELECT 1 FROM information_schema.columns
        WHERE table_schema = 'public' AND table_name = 'projects' AND column_name = 'student_id'
     ) THEN
    ALTER TABLE public.projects RENAME TO neon_sample_projects_legacy;
  END IF;
END
$$;

CREATE TABLE IF NOT EXISTS projects (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  college_id BIGINT NOT NULL REFERENCES colleges(id),
  title TEXT NOT NULL CHECK (char_length(btrim(title)) BETWEEN 3 AND 200),
  description TEXT NOT NULL,
  features TEXT,
  technologies TEXT[] NOT NULL DEFAULT '{}',
  department TEXT NOT NULL DEFAULT 'Unassigned',
  year_batch TEXT,
  domain TEXT,
  team_name TEXT,
  faculty_guide_id UUID NOT NULL REFERENCES profiles(id),
  faculty_guide_name TEXT,
  student_id UUID NOT NULL REFERENCES profiles(id),
  student_name TEXT,
  team_members TEXT[] NOT NULL DEFAULT '{}',
  status TEXT NOT NULL DEFAULT 'pending'
    CHECK (status IN ('pending', 'approved', 'submitted', 'verified', 'changes_requested', 'rejected')),
  github_url TEXT,
  demo_url TEXT,
  report_path TEXT,
  demo_video_path TEXT,
  faculty_feedback TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS projects_student_created_idx ON projects(student_id, created_at DESC);
CREATE INDEX IF NOT EXISTS projects_faculty_status_idx ON projects(faculty_guide_id, status, updated_at DESC);
CREATE INDEX IF NOT EXISTS projects_catalogue_idx ON projects(status, created_at DESC);
CREATE INDEX IF NOT EXISTS projects_college_idx ON projects(college_id);

CREATE TABLE IF NOT EXISTS external_project_references (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  owner_id UUID NOT NULL REFERENCES profiles(id) ON DELETE CASCADE,
  title TEXT NOT NULL CHECK (char_length(btrim(title)) BETWEEN 1 AND 200),
  source_type TEXT NOT NULL CHECK (source_type IN ('website', 'github')),
  source_url TEXT NOT NULL CHECK (char_length(source_url) <= 2048),
  content_text TEXT NOT NULL CHECK (char_length(content_text) BETWEEN 20 AND 80000),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UNIQUE (owner_id, source_url)
);

CREATE INDEX IF NOT EXISTS external_project_references_owner_created_idx
  ON external_project_references(owner_id, created_at DESC);

CREATE TABLE IF NOT EXISTS project_team_members (
  id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  project_id UUID NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
  member_name TEXT NOT NULL,
  member_email TEXT NOT NULL DEFAULT '',
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS project_team_project_idx ON project_team_members(project_id);

CREATE TABLE IF NOT EXISTS project_reviews (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  project_id UUID NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
  faculty_id UUID NOT NULL REFERENCES profiles(id),
  review_type TEXT NOT NULL CHECK (review_type IN ('proposal', 'final')),
  decision TEXT NOT NULL CHECK (decision IN ('approved', 'verified', 'rejected', 'changes_requested')),
  comments TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  reviewed_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS project_reviews_project_idx
  ON project_reviews(project_id, review_type, decision, reviewed_at DESC);

CREATE TABLE IF NOT EXISTS faq_questions (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id UUID NOT NULL REFERENCES profiles(id) ON DELETE CASCADE,
  question TEXT NOT NULL CHECK (char_length(btrim(question)) BETWEEN 8 AND 1500),
  answer TEXT,
  status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'published', 'rejected')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  answered_at TIMESTAMPTZ,
  answered_by UUID REFERENCES profiles(id)
);

CREATE INDEX IF NOT EXISTS faq_questions_public_idx
  ON faq_questions(status, answered_at DESC);

CREATE TABLE IF NOT EXISTS project_files (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  storage_key TEXT NOT NULL UNIQUE,
  project_id UUID NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
  owner_id UUID NOT NULL REFERENCES profiles(id) ON DELETE CASCADE,
  original_name TEXT NOT NULL,
  content_type TEXT NOT NULL,
  byte_size BIGINT NOT NULL CHECK (byte_size >= 0),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS project_files_project_idx ON project_files(project_id);
